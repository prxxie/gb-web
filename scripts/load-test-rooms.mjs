#!/usr/bin/env node
/**
 * `US-OPS-003` — prove the launch load: fifty rooms at the same time.
 *
 * The story's number is **50 concurrent rooms**, each with two seats, so the run drives the real API: mint a session, create
 * a room, seat a second player, open both sockets and wait until the room reports two members. A room counts as ready when
 * the *socket* says so — `POST /rooms` only names a room, the roster lives in the Durable Object
 * (`docs/02-reference/api/rooms.md`), so a run that stopped at the HTTP call would prove nothing about the thing under load.
 *
 * Every virtual player mints its session from its own `cf-connecting-ip`. `NFR-25` allows 30 sessions/min per address and
 * 10 room creates/min per address; one address for a hundred players would measure the rate limiter instead of the rooms,
 * and the 429s would read as a capacity failure.
 *
 * Usage:
 *   node scripts/load-test-rooms.mjs                       # 50 rooms against the local worker
 *   node scripts/load-test-rooms.mjs --rooms 50 --base https://api.example.com/api/v1
 *   node scripts/load-test-rooms.mjs --concurrency 10 --out docs/06-reports/load/run.md
 *
 * Exit code 1 when the error rate passes `--max-error-rate` (default 2 %) or p95 latency passes `--max-p95-ms`
 * (default 3000): the report is evidence, the red run is the alarm.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;

/** Nearest-rank percentile: small samples stay honest, and the p95 of 50 rooms is a real room, not an interpolation. */
export function percentile(values, share) {
  if (values.length === 0) return null;
  const sorted = [...values].sort((left, right) => left - right);
  const rank = Math.ceil((share / 100) * sorted.length);
  return sorted[Math.min(sorted.length - 1, Math.max(0, rank - 1))];
}

/** The numbers the report and the exit code are decided on. Pure, so a case can pin them without a network. */
export function summarise(runs, budget = { maxErrorRate: 0.02, maxP95Ms: 3000 }) {
  const ok = runs.filter((run) => run.ok);
  const latencies = ok.map((run) => run.readyMs);
  const errorRate = runs.length === 0 ? 1 : (runs.length - ok.length) / runs.length;
  const p95 = percentile(latencies, 95);
  const failures = new Map();
  for (const run of runs) {
    if (run.ok) continue;
    const key = run.reason ?? "unknown";
    failures.set(key, (failures.get(key) ?? 0) + 1);
  }
  const breached = errorRate > budget.maxErrorRate || (p95 !== null && p95 > budget.maxP95Ms);
  return {
    rooms: runs.length,
    ready: ok.length,
    errorRate,
    p50: percentile(latencies, 50),
    p95,
    p99: percentile(latencies, 99),
    max: latencies.length === 0 ? null : Math.max(...latencies),
    failures: [...failures.entries()].sort((left, right) => right[1] - left[1]),
    breached,
  };
}

export function renderReport(summary, meta) {
  const row = (label, value) => `| ${label} | ${value === null ? "—" : value} |`;
  const failures =
    summary.failures.length === 0
      ? "_No failed rooms._"
      : ["| Reason | Rooms |", "|---|---|", ...summary.failures.map(([reason, count]) => `| \`${reason}\` | ${count} |`)].join("\n");
  return `# Load test — ${meta.rooms} rooms — ${meta.date}

Generated by \`scripts/load-test-rooms.mjs\` (\`US-OPS-003\`). Target \`${meta.base}\`, concurrency ${meta.concurrency},
${meta.seats} seats per room, ${meta.local ? "**local** (spoofed per-player addresses)" : `mints paced at ${meta.sessionsPerMinute}/min and room creates at ${meta.roomsPerMinute}/min, the real per-address limits`}.

| Measure | Value |
|---|---|
${row("Rooms attempted", summary.rooms)}
${row("Rooms ready (both seats in the roster)", summary.ready)}
${row("Error rate", `${(summary.errorRate * 100).toFixed(1)} %`)}
${row("Ready p50", summary.p50 === null ? null : `${summary.p50} ms`)}
${row("Ready p95", summary.p95 === null ? null : `${summary.p95} ms`)}
${row("Ready p99", summary.p99 === null ? null : `${summary.p99} ms`)}
${row("Ready max", summary.max === null ? null : `${summary.max} ms`)}

**Verdict: ${summary.breached ? "BREACH" : "inside budget"}** — budgets: error rate ≤ ${(meta.maxErrorRate * 100).toFixed(0)} %,
p95 ≤ ${meta.maxP95Ms} ms.

## Failures

${failures}
`;
}

function parseArgs(argv) {
  const args = {
    rooms: 50,
    concurrency: 25,
    seats: 2,
    // `AC2` asks for a ten-minute soak with 400 sockets. The soak path is written but **not verified** here: a run with
    // eight seats hung for ~105 s per room in this environment, and shipping a number I could not reproduce is worse than
    // naming the gap. `--soak-seconds` stays available for the run that closes it.
    soakSeconds: 0,
    repeat: 1,
    local: false,
    sessionsPerMinute: 25,
    roomsPerMinute: 9,
    base: process.env.GBW_API_BASE ?? "http://127.0.0.1:8787/api/v1",
    out: null,
    maxErrorRate: 0.02,
    maxP95Ms: 3000,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const next = argv[index + 1];
    if (argv[index] === "--rooms") args.rooms = Number(next);
    if (argv[index] === "--concurrency") args.concurrency = Number(next);
    if (argv[index] === "--seats") args.seats = Number(next);
    if (argv[index] === "--soak-seconds") args.soakSeconds = Number(next);
    if (argv[index] === "--repeat") args.repeat = Number(next);
    if (argv[index] === "--sessions-per-minute") args.sessionsPerMinute = Number(next);
    if (argv[index] === "--rooms-per-minute") args.roomsPerMinute = Number(next);
    if (argv[index] === "--local") args.local = true;
    if (argv[index] === "--base") args.base = String(next).replace(/\/$/, "");
    if (argv[index] === "--out") args.out = next ?? null;
    if (argv[index] === "--max-error-rate") args.maxErrorRate = Number(next);
    if (argv[index] === "--max-p95-ms") args.maxP95Ms = Number(next);
  }
  return args;
}

/**
 * A distinct address per virtual player, for **local** runs only.
 *
 * `wrangler dev` trusts whatever `cf-connecting-ip` it is handed, so a local run can mint a hundred sessions without
 * tripping `NFR-25`. Production cannot: Cloudflare's edge answers a client-supplied `cf-connecting-ip` with its own `403`
 * before the worker ever sees the request, so a run against a deployed worker must pace itself inside the real limit
 * instead of pretending to be many addresses. That difference is why `--local` exists and why the report states which mode
 * produced the number.
 *
 * The index must be **globally** unique across the run: seeding it per room (`room * 2 + seat`) made neighbouring rooms
 * share an address once a room had more than two seats, and the run then measured the rate limiter instead of the rooms.
 */
function addressFor(index) {
  return `198.18.${Math.floor(index / 200)}.${(index % 200) + 1}`;
}

/**
 * A shared clock that keeps session mints under the documented per-address limit (`NFR-25`: 30/min). Without it a
 * fifty-room run asks for a hundred sessions in a second and measures its own 429s.
 */
function makePacer(perMinute) {
  const interval = perMinute > 0 ? 60_000 / perMinute : 0;
  let next = 0;
  return async () => {
    if (interval === 0) return;
    const now = Date.now();
    const wait = Math.max(0, next - now);
    next = Math.max(now, next) + interval;
    if (wait > 0) await new Promise((resolve) => setTimeout(resolve, wait));
  };
}

async function post(base, path, token, body, address) {
  const response = await fetch(`${base}${path}`, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      // Only a local `wrangler dev` accepts this; a deployed worker is fronted by an edge that 403s it.
      ...(address === null ? {} : { "cf-connecting-ip": address }),
      ...(token === null ? {} : { authorization: `Bearer ${token}` }),
    },
    body: JSON.stringify(body ?? {}),
  });
  const text = await response.text();
  if (!response.ok) throw new Error(`${path} ${response.status} ${text.slice(0, 120)}`);
  return text === "" ? {} : JSON.parse(text);
}

/** Exposed for `TC-OPS-909`: the case pins the header rule without a network. */
export async function mintForTest(base, address, pace) {
  return mintSession(base, address, pace);
}

export const makePacerForTest = makePacer;

async function mintSession(base, address, pace) {
  await pace();
  const { sessionToken } = await post(base, "/sessions", null, { displayName: "Tải" }, address);
  return sessionToken;
}

/**
 * Resolves when the socket reports a roster of `seats` members, then **holds the socket open** for the soak window
 * (`AC2`: the run continues and no socket is closed by the server). A socket the server drops during the soak is a
 * failure with its close code, because that is the thing a load test exists to find.
 */
function openSeat(wsUrl, token, displayName, seats, timeoutMs, soakMs) {
  return new Promise((resolve, reject) => {
    const socket = new WebSocket(wsUrl);
    let ready = false;
    let closeCode = null;
    const timer = setTimeout(() => {
      socket.close();
      reject(new Error(ready ? "soak-timeout" : "roster-timeout"));
    }, timeoutMs + soakMs);
    const finish = (error) => {
      clearTimeout(timer);
      try {
        socket.close();
      } catch {
        /* already closing */
      }
      if (error) reject(error);
      else resolve({ dropped: closeCode });
    };
    socket.addEventListener("open", () => socket.send(JSON.stringify({ t: "auth", token, displayName })));
    socket.addEventListener("error", () => finish(new Error("socket-error")));
    socket.addEventListener("close", (event) => {
      closeCode = event.code;
      // A close after the soak began is the finding; a close before the roster arrived is already a failure.
      if (ready) finish(null);
      else finish(new Error(`closed:${event.code}`));
    });
    socket.addEventListener("message", (event) => {
      let frame;
      try {
        frame = JSON.parse(String(event.data));
      } catch {
        return;
      }
      if (frame.t === "error" || frame.t === "rejected") {
        finish(new Error(`${frame.t}:${frame.code ?? frame.reason ?? "unknown"}`));
        return;
      }
      const members = frame.room?.members?.length ?? frame.members?.length ?? 0;
      if (!ready && members >= seats) {
        ready = true;
        if (soakMs <= 0) finish(null);
        else setTimeout(() => finish(null), soakMs);
      }
    });
  });
}

async function runRoom(base, index, seats, timeoutMs, soakMs, options) {
  const firstPlayer = index * seats;
  const addressForSeat = (seat) => (options.local ? addressFor(firstPlayer + seat) : null);

  // Every session is minted **before** the room exists. Minting is paced (30/min per address) and the guest's token is only
  // needed after the room is created, so doing it in between put the pacer's queueing time inside the room's own latency —
  // the run reported p50 10 s and p95 52 s for rooms that were up in well under a second.
  const hostToken = await mintSession(base, addressForSeat(0), options.paceSession);
  const guestTokens = [];
  for (let seat = 1; seat < seats; seat += 1) {
    guestTokens.push(await mintSession(base, addressForSeat(seat), options.paceSession));
  }

  // Room creation is the tighter per-address limit (`NFR-25`: 10/min against 30 for sessions), so it has its own pacer.
  // The clock starts after that wait: the wait is the rate limiter's cost, not the room's latency.
  await options.paceRoom();
  const startedAt = Date.now();
  const created = await post(base, "/rooms", hostToken, { maxPlayers: seats }, addressForSeat(0));

  // Joins carry no per-address limit (`RULES` in `apps/worker/src/lib/ratelimit.ts`), so they are measured as they are.
  const guests = [];
  for (const [offset, token] of guestTokens.entries()) {
    const joined = await post(
      base,
      `/rooms/${created.roomCode}/join`,
      token,
      { displayName: `Tải ${offset + 1}`, mobileId: "mbl-01", avatarId: "av-01" },
      addressForSeat(offset + 1),
    );
    guests.push({ token, wsUrl: joined.wsUrl, playerId: joined.playerId });
  }

  // The room is only "ready" when the Durable Object says every seat is in the roster, so the sockets are the clock — and
  // they stay open for the soak window, which is what `AC2` asks about.
  const sockets = [
    openSeat(created.wsUrl, hostToken, "Tải chủ", seats, timeoutMs, soakMs),
    ...guests.map((guest, offset) => openSeat(guest.wsUrl, guest.token, `Tải ${offset + 1}`, seats, timeoutMs, soakMs)),
  ];
  const settled = await Promise.all(sockets);
  const readyMs = Date.now() - startedAt - soakMs;
  const dropped = settled.filter((seat) => seat.dropped !== null && seat.dropped !== 1000 && seat.dropped !== 1005).length;
  return { ok: true, readyMs, roomCode: created.roomCode, seats: settled.length, dropped };
}

async function mapWithLimit(items, limit, worker) {
  const results = new Array(items.length);
  let cursor = 0;
  const runners = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      try {
        results[index] = await worker(index);
      } catch (error) {
        // Keep enough of the message to act on: `"/sessions"` alone hid the 429 that the first run tripped.
        results[index] = { ok: false, reason: error instanceof Error ? error.message.slice(0, 60) : "unknown" };
      }
    }
  });
  await Promise.all(runners);
  return results;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const timeoutMs = 15_000;
  const startedAt = Date.now();
  const paceSession = makePacer(args.local ? 0 : args.sessionsPerMinute);
  const paceRoom = makePacer(args.local ? 0 : args.roomsPerMinute);
  const runs = await mapWithLimit(Array.from({ length: args.rooms }, (_, index) => index), args.concurrency, (index) =>
    runRoom(args.base, index, args.seats, timeoutMs, args.soakSeconds * 1000, {
      local: args.local,
      paceSession,
      paceRoom,
    }),
  );
  const summary = summarise(runs, { maxErrorRate: args.maxErrorRate, maxP95Ms: args.maxP95Ms });
  const date = new Date().toISOString().slice(0, 10);
  const report = renderReport(summary, { ...args, date, maxErrorRate: args.maxErrorRate, maxP95Ms: args.maxP95Ms });
  const out = args.out ?? join(ROOT, "docs", "06-reports", "load", `${date}-rooms.md`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, report, "utf8");

  const elapsed = Date.now() - startedAt;
  process.stdout.write(
    `${summary.ready}/${summary.rooms} rooms ready · error ${(summary.errorRate * 100).toFixed(1)} % · p50 ${summary.p50} ms · ` +
      `p95 ${summary.p95} ms · max ${summary.max} ms · ${elapsed} ms wall\n${out}${summary.breached ? " (BREACH)" : ""}\n`,
  );
  process.exitCode = summary.breached ? 1 : 0;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
